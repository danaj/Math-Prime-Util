#!/usr/bin/env perl
use strict;
use warnings;

my $limit = 1 << 18;
my $blocks = int($limit / 240) + 1;  # Eight mod-30 bytes per rank entry.
my $end = 240 * $blocks - 1;
my $composite = '';
vec($composite,1,1) = 1;
for my $p (2 .. int(sqrt($end))) {
  next if vec($composite,$p,1);
  for (my $n = $p*$p; $n <= $end; $n += $p) {
    vec($composite,$n,1) = 1;
  }
}

my @residues = (1,7,11,13,17,19,23,29);
my (@rank, @bytes);
my $count = 3;  # 2, 3, and 5 are not in the wheel.
for my $block (0 .. $blocks-1) {
  push @rank, $count;
  for my $pos (0 .. 7) {
    my $base = 240*$block + 30*$pos;
    my $byte = 0;
    for my $bit (0 .. $#residues) {
      next if vec($composite,$base+$residues[$bit],1);
      $byte |= 1 << $bit;
      ++$count;
    }
    push @bytes, $byte;
  }
}
die "Prime count ranks do not fit in uint16_t" if $rank[-1] > 65535;

print <<"HEADER";
#ifndef MPU_PRIME_COUNT_SMALL_H
#define MPU_PRIME_COUNT_SMALL_H

/* Generated by perl xt/make-prime-count-small.pl. */
#define PRIME_COUNT_SMALL_LIMIT $limit

/* A set bit denotes a prime at the corresponding mod-30 residue. */
static const uint32_t pc_small_bits[] = {
HEADER
my @words = unpack('V*', pack('C*',@bytes));
while (@words) {
  printf "  %s,\n", join(',', map {sprintf "0x%08xU", $_} splice(@words,0,6));
}
print "};\n\n/* Count before each group of eight wheel bytes, including 2, 3, and 5. */\n";
print "static const uint16_t pc_small_rank[] = {\n";
while (@rank) {
  printf "  %s,\n", join(',', splice(@rank,0,12));
}
print "};\n\n#endif\n";
